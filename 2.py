import tkinter as tk

window = tk.Tk()
window.title('Hello')
window.geometry('1400x580')
window.configure(bg='green')
button = tk.Button(
    window,
    text='YOURRR',
    font=('Arial',45)
)
button.pack(pady=45)

window.mainloop()



